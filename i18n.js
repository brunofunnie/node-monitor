function translate(language, key, values = {}) {
  const messages = languages.find(item => item.id === language)?.messages || languages[0].messages;
  return (messages[key] || languages[0].messages[key] || key).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}
